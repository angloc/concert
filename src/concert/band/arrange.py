# part -> list of phrases; phrase = dict(players, notes[(t0,t1,midi,(a,b,c),opts)])
strings = []


def phrase(part, kind, players, notes, gain=1.0):
    """Add one bowed phrase for `part`, played by `players`; every long tone breathes in loudness."""
    out = []
    for n in notes:
        o = dict(n[4]) if len(n) > 4 else {}
        a, b, c = n[3]
        if (
            b > 0.2 and n[1] - n[0] > 0.8
        ):  # every long tone breathes: a little less, more, less
            a *= 0.86
            b = min(1.0, b * 1.10)
            c *= 0.90
        if players > 1 and o.get("port", 0) > 0.07:
            o["port"] *= (
                0.6  # a section slides less than a soloist, or it sings like a saw
            )
        if part == "S":
            o["vib"] = o.get("vib", 22) * 0.72
        out.append(dict(t=n[0], d=n[1] - n[0], m=n[2], dyn=(a, b, c), **o))
    t = notes[0][0]
    gain *= (
        0.80 if 50.5 < t < 59 or 119 < t < 127 else 0.92 if 111 < t < 119 else 1.0
    )  # climaxes: weight from the bow, not from the fader
    strings.append(
        {"part": part, "kind": kind, "players": players, "notes": out, "gain": gain}
    )


def seq(line, *ev):
    """ev: (e0,e1,midi,dyn3[,opts]) -> absolute"""
    return [
        (T(line, x[0]), T(line, x[1]), x[2], x[3]) + ((x[4],) if len(x) > 4 else ())
        for x in ev
    ]


