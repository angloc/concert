"""arrange.py - the written part. Everything is placed in (line, eighth) on the singer's own rubato clock taken from build/score.json.
In every line: eighths 0-2 pickup, 3 = first downbeat, 11 = second downbeat, 15 = the breath, 16 = next line's pickup."""

import itertools
import json
import os
import random
from pathlib import Path

from concert import ROOT
from concert.performance import score as SC

sc = json.loads(Path(os.path.join(ROOT, "build", "score.json")).read_text())
TOTAL = sc["total"]
E8 = sc["e8"]

MAP = []
for L, W in zip(sc["lines"], SC.V1 + SC.V2):
    e = 0.0
    pts = []
    k = 0
    flat = [n for s in L["syl"] for n in s["notes"]]
    for s in W["syl"]:
        for nm, ei in s["notes"]:
            pts.append((e, flat[k]["t"]))
            e += ei
            k += 1
    pts.append((e, L["t1"]))
    MAP.append(pts)


def T(line, e):
    """Time in seconds of eighth `e` of line `line` on the singer's rubato clock, extrapolated past the line's end."""
    p = MAP[line]
    end = p[-1][0]
    if e > end:
        if line + 1 < len(MAP) and end == 15:
            if e >= 16:
                return T(line + 1, e - 16)
            return p[-1][1] + (MAP[line + 1][0][1] - p[-1][1]) * (e - 15)
        return p[-1][1] + (e - end) * E8 * 1.15
    for (a, ta), (b, tb) in itertools.pairwise(p):
        if e <= b:
            return ta + (tb - ta) * (e - a) / (b - a)
    return p[-1][1]


# =================================================================== HARP
harp = []  # (t, midi, vel, kind, ring-limit)
rh = random.Random(21)


def at(t, m, v, kind="pluck", ring=None):
    """Add one harp note at time `t` (MIDI `m`, velocity `v`) with a little human timing and velocity spread."""
    harp.append(
        [
            t + rh.gauss(0, 0.007),
            m,
            max(0.08, min(0.95, v + rh.gauss(0, 0.022))),
            kind,
            ring,
        ]
    )


def h(line, *ev, dv=0.0, lay=0.0):
    """ev: (e, midi, vel[, kind]). `lay` = lay-back in seconds (sits a hair behind the singer)"""
    for x in ev:
        kind = x[3] if len(x) > 3 else "pluck"
        ring = x[4] if len(x) > 4 else None
        at(T(line, x[0]) + lay, x[1], x[2] + dv, kind, ring)


def roll(line, e, mids, v, spread=0.055, lay=0.0, dv=0.0):
    """Add a rolled harp chord at eighth `e` of `line`, the notes spread around the beat."""
    t = T(line, e) + lay
    for k, m in enumerate(mids):
        at(
            t + (k - (len(mids) - 1) * 0.35) * spread,
            m,
            v * (0.82 + 0.18 * k / max(1, len(mids) - 1)) + dv,
        )


def flow(line, e0, step, mids, v0, v1, lay=0.0):
    """Add harp notes one `step` of eighths apart from eighth `e0`, with velocity moving from `v0` to `v1`."""
    n = len(mids)
    for k, m in enumerate(mids):
        at(T(line, e0 + k * step) + lay, m, v0 + (v1 - v0) * k / max(1, n - 1))


